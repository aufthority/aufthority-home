#!/usr/bin/env python3
"""Build the /donate page for every Aufthority app from one template.

Usage (from the folder that holds all the app repos side by side):
    python3 aufthority-home/tools/donate/build.py            # all apps
    python3 aufthority-home/tools/donate/build.py nafaslega  # one or more slugs

Edit apps.json (links, payee, app list) or template.html (copy, layout),
then re-run. It also refreshes the compact support block on each app's
results screen (between the auf-support:start/end comments in the app's
index.html). Each page is written to <root>/<app.out>/index.html, where
<root> is the parent of the aufthority-home repo.
"""
import base64, html, json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]  # .../aufthority-home/tools/donate -> parent of aufthority-home

cfg = json.loads((HERE / "apps.json").read_text(encoding="utf-8"))
template = (HERE / "template.html").read_text(encoding="utf-8")
qr = "data:image/png;base64," + base64.b64encode((HERE / "toyyibpay-qr.png").read_bytes()).decode()
apps = cfg["apps"]
wanted = set(sys.argv[1:]) or {a["slug"] for a in apps}
unknown = wanted - {a["slug"] for a in apps}
if unknown:
    sys.exit(f"Unknown app slug(s): {', '.join(sorted(unknown))}")


def app_list(current):
    rows = []
    for a in apps:
        here = ('<span class="here"><span data-ms>Anda di sini</span>'
                '<span data-en>You are here</span></span>') if a is current else ""
        rows.append(
            f'        <li><a href="{a["url"]}" data-umami-event="{html.escape(current["name"])} - Donate Other app">'
            f'<span class="app-name">{html.escape(a["name"])}{here}</span>'
            f'<span class="app-tag"><span data-ms>{html.escape(a["tag_ms"])}</span>'
            f'<span data-en>{html.escape(a["tag_en"])}</span></span></a></li>')
    return "\n".join(rows)


START, END = "<!-- auf-support:start -->", "<!-- auf-support:end -->"

SUPPORT_CSS = """<style>
  .auf-support { box-sizing: border-box; max-width: 560px; margin: 36px auto 28px; padding: 22px;
    border: 1px solid rgba(127,127,127,.35); border-radius: 2px; text-align: left; color: inherit; font: inherit; }
  .auf-support * { box-sizing: border-box; }
  .auf-support h3 { margin: 0 0 6px; font-size: 1.15em; line-height: 1.3; color: inherit; }
  .auf-support p { margin: 0; font-size: .92em; line-height: 1.55; opacity: .85; }
  .auf-support .auf-support-row { display: flex; gap: 16px; align-items: center; margin-top: 16px; }
  .auf-support .auf-support-qr { flex: 0 0 auto; background: #fff; padding: 6px; border-radius: 2px; line-height: 0; }
  .auf-support .auf-support-qr img { width: 84px; height: 84px; image-rendering: pixelated; display: block; }
  .auf-support .auf-support-btns { display: flex; flex-direction: column; gap: 8px; flex: 1; min-width: 0; }
  .auf-support a.auf-support-btn { display: block; text-align: center; padding: 11px 14px; border-radius: 2px;
    font-weight: 600; font-size: .92em; line-height: 1.2; text-decoration: none; background: #2d6a4f; color: #fff;
    border: 1px solid #2d6a4f; }
  .auf-support a.auf-support-btn.ghost { background: transparent; color: inherit; border-color: rgba(127,127,127,.45); }
  .auf-support a.auf-support-btn:hover { opacity: .88; }
  .auf-support .auf-support-small { margin-top: 12px; font-size: .8em; opacity: .7; }
  .auf-support .auf-support-small a { color: inherit; }
  @media (max-width: 380px) { .auf-support .auf-support-qr { display: none; } }
  @media print { .auf-support { display: none !important; } }
</style>"""


def support_block(app):
    mode, name = app["resultsLang"], html.escape(app["name"])

    def t(en, ms, key):
        if mode == "spans":
            return f"<span data-en>{en}</span><span data-bm>{ms}</span>"
        if mode == "i18n":  # NafasLega: text comes from its own i18n dictionary (keys added there)
            return f'<span data-i18n="{key}">{en}</span>'
        return ms if mode == "ms" else en

    ev = f"{name} - Results Donate"
    return f"""{START}
<!-- Generated by aufthority-home/tools/donate/build.py: edit there, not here. -->
<section class="auf-support" aria-label="Support {name}">
{SUPPORT_CSS}
  <h3>{t("Was this useful?", "Adakah ini membantu?", "supTitle")}</h3>
  <p>{t(f"{name} is free and built by one person. A small contribution keeps it free and funds new evidence-based tools for Malaysians.",
        f"{name} percuma dan dibina oleh seorang individu. Sumbangan kecil membantu mengekalkannya percuma dan membina alat baharu berasaskan bukti untuk rakyat Malaysia.", "supText")}</p>
  <div class="auf-support-row">
    <div class="auf-support-qr"><img src="{qr}" alt="QR ToyyibPay" width="84" height="84"></div>
    <div class="auf-support-btns">
      <a class="auf-support-btn" href="{cfg["toyyibpay"]}" target="_blank" rel="noopener" data-umami-event="{ev} ToyyibPay">{t("Donate via ToyyibPay (FPX / DuitNow)", "Derma melalui ToyyibPay (FPX / DuitNow)", "supToyyib")}</a>
      <a class="auf-support-btn ghost" href="{cfg["bmc"]}" target="_blank" rel="noopener" data-umami-event="{ev} BMC">{t("Buy me a coffee (outside Malaysia)", "Belanja kopi (luar Malaysia)", "supBmc")}</a>
    </div>
  </div>
  <p class="auf-support-small">{t("Optional. Every tool stays free.", "Pilihan sahaja. Setiap alat kekal percuma.", "supOptional")} <a href="{app["url"]}donate/" data-umami-event="{ev} More">{t("More ways to support", "Cara lain untuk menyokong", "supMore")}</a></p>
</section>
{END}"""


def inject_support(app):
    target = ROOT / app["out"] / ".." / "index.html"
    target = target.resolve()
    src = target.read_text(encoding="utf-8")
    if src.count(START) != 1 or src.count(END) != 1:
        print(f"skip results block for {app['slug']}: markers not found in {target.name}")
        return
    i, j = src.index(START), src.index(END) + len(END)
    new = src[:i] + support_block(app) + src[j:]
    if new != src:
        target.write_text(new, encoding="utf-8")
    print(f"results block {app['slug']}: {'updated' if new != src else 'unchanged'}")


for app in apps:
    if app["slug"] not in wanted:
        continue
    if (ROOT / app["out"]).parent.exists():
        inject_support(app)
    page = template
    for key, val in {
        "{{NAME}}": html.escape(app["name"]),
        "{{URL}}": app["url"],
        "{{UMAMI}}": app["umami"],
        "{{LANG}}": app["defaultLang"],
        "{{LANGKEY}}": app["langKey"],
        "{{PAYEE}}": html.escape(cfg["payee"]),
        "{{TOYYIBPAY}}": cfg["toyyibpay"],
        "{{BMC}}": cfg["bmc"],
        "{{QR}}": qr,
        "{{COUNT}}": str(len(apps)),
        "{{APPS}}": app_list(app),
    }.items():
        page = page.replace(key, val)
    assert "{{" not in page, f"unfilled placeholder in {app['slug']}"
    out = ROOT / app["out"] / "index.html"
    if not out.parent.parent.exists():
        print(f"skip {app['slug']}: {out.parent.parent} not found (repo not cloned here)")
        continue
    out.parent.mkdir(exist_ok=True)
    out.write_text(page, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")
